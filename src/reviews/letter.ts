import { Excerpt, safeLatex } from './changes';
import { ReviewsFile } from './format';

export interface LetterItemContext {
  /** Where the comment is attached, for "(main.tex, line 42)". */
  file?: string;
  /** The revised paragraph, if it changed since the submitted version. */
  excerpt?: Excerpt;
}

export function generateLetter(reviews: ReviewsFile, context: Map<string, LetterItemContext>, source: string): string {
  const all = reviews.reviewers.flatMap((r) => r.items);
  const open = all.filter((i) => !i.done).length;
  const out: string[] = [
    `% Response letter generated by TeX Margin from ${source}.`,
    `% Edit the responses there and regenerate; changes made here are overwritten.`,
    `% ${all.length - open} of ${all.length} comments addressed${open ? `, ${open} still open` : ''}.`,
    '\\documentclass[11pt]{article}',
    '\\usepackage[margin=2.5cm]{geometry}',
    '\\usepackage[T1]{fontenc}',
    '\\usepackage[utf8]{inputenc}',
    '\\usepackage{xcolor}',
    '\\usepackage{parskip}',
    '\\newenvironment{reviewercomment}{\\begin{quote}\\itshape}{\\end{quote}}',
    '\\newenvironment{revisedtext}{\\begin{quote}\\small\\color{blue!50!black}}{\\end{quote}}',
    '\\newcommand{\\todo}[1]{\\textcolor{red}{[TODO: #1]}}',
    '',
    '\\begin{document}',
    '',
    `\\section*{Response to the Reviewers${reviews.title ? `: ${escapeLatex(reviews.title)}` : ''}}`,
    '',
    'We thank the reviewers for their comments. Below, we respond to each comment in turn; text in',
    'blue is quoted from the revised manuscript.',
  ];
  for (const reviewer of reviews.reviewers) {
    out.push('', `\\section*{${escapeLatex(reviewer.name)}}`);
    for (const item of reviewer.items) {
      const ctx = context.get(item.label);
      out.push('', `\\subsection*{${escapeLatex(item.label)}}`, '\\begin{reviewercomment}', escapeLatex(item.comment), '\\end{reviewercomment}', '');
      out.push(`\\textbf{Response.} ${item.response || `\\todo{respond${item.done ? '' : '; still open'}}`}`);
      if (ctx?.excerpt) {
        const where = `${ctx.file ? `\\texttt{${escapeLatex(ctx.file)}}, ` : ''}line ${ctx.excerpt.line}`;
        out.push('', `\\textbf{Revised text} (${where}):`);
        if (safeLatex(ctx.excerpt.text)) out.push('\\begin{revisedtext}', ctx.excerpt.text, '\\end{revisedtext}');
        else out.push('\\begin{quote}\\small', '\\begin{verbatim}', ctx.excerpt.text.replace(/\\end\{verbatim\}/g, '\\end {verbatim}'), '\\end{verbatim}', '\\end{quote}');
      }
    }
  }
  out.push('', '\\end{document}', '');
  return out.join('\n');
}

/** Plain text → LaTeX. Paragraph breaks stay. */
export function escapeLatex(text: string): string {
  return text
    .replace(/\\/g, '\u0000')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/\u0000/g, '\\textbackslash{}')
    .replace(/"([^"\n]+)"/g, "``$1''");
}
